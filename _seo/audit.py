#!/usr/bin/env python3
"""
Regenerate _seo/content-inventory.md from the built site.

    bundle exec jekyll build && python3 _seo/audit.py

Reads _site/, never the source, so it reports what actually ships. Checks the
things that silently rot: missing/oversized titles and descriptions, duplicate
metadata, missing H1s, pages that lost their structured data, and noindex pages
that leaked schema they should not have.
"""
import re, glob, os, html, sys, datetime
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, '_site')
if not os.path.isdir(SITE):
    sys.exit("No _site/ - run `bundle exec jekyll build` first.")

TITLE_MAX, DESC_MAX = 60, 160

def text(m):
    return html.unescape(re.sub(r'<[^>]+>', '', m).strip()) if m else None

pages = []
for f in sorted(glob.glob(os.path.join(SITE, '**/*.html'), recursive=True)):
    s = open(f, encoding='utf-8', errors='replace').read()
    rel = os.path.relpath(f, SITE)
    url = '/' + rel.replace('index.html', '').replace('\\', '/')
    t = re.search(r'<title>(.*?)</title>', s, re.S)
    d = re.search(r'<meta name="description" content="(.*?)"', s, re.S)
    h1 = re.search(r'<h1[^>]*>(.*?)</h1>', s, re.S)
    graph = '"@graph"' in s
    types = sorted(set(re.findall(r'"@type":"([A-Za-z]+)"', s))) if graph else []
    pages.append({
        'url': url,
        'title': text(t.group(1)) if t else None,
        'desc': text(d.group(1)) if d else None,
        'h1': text(h1.group(1)) if h1 else None,
        'schema': types,
        'noindex': bool(re.search(r'name="robots"[^>]*noindex', s)),
        'canonical': 'rel="canonical"' in s,
        'og': 'og:title' in s,
    })

live = [p for p in pages if not p['noindex']]
issues = []
for p in live:
    for key, cap, label in (('title', TITLE_MAX, 'Title'), ('desc', DESC_MAX, 'Description')):
        v = p[key]
        if not v:            issues.append((p['url'], f'{label} missing'))
        elif len(v) > cap:   issues.append((p['url'], f'{label} {len(v)} chars (max {cap})'))
    if not p['h1']:          issues.append((p['url'], 'No H1'))
    if not p['schema']:      issues.append((p['url'], 'No structured data'))
    if not p['canonical']:   issues.append((p['url'], 'No canonical'))
    if not p['og']:          issues.append((p['url'], 'No Open Graph'))
for p in pages:
    if p['noindex'] and p['schema']:
        issues.append((p['url'], 'noindex page still emits an @graph'))

for field, label in (('title', 'title'), ('desc', 'description'), ('h1', 'H1')):
    seen = defaultdict(list)
    for p in live:
        if p[field]: seen[p[field]].append(p['url'])
    for val, urls in seen.items():
        if len(urls) > 1:
            issues.append((', '.join(urls), f'Duplicate {label}: "{val[:50]}..."'))

out = [f"# Content inventory",
       "",
       f"Generated by `_seo/audit.py` on {datetime.date.today().isoformat()}. Do not hand-edit;",
       "re-run the script instead.",
       "",
       f"**{len(live)} indexable pages, {len(pages) - len(live)} noindex.**",
       ""]

out += ["## Issues", ""]
if issues:
    for u, why in sorted(issues): out.append(f"- `{u}` - {why}")
else:
    out.append("None. Every indexable page has a unique title within "
               f"{TITLE_MAX} chars, a unique description within {DESC_MAX}, an H1, "
               "structured data, a canonical and Open Graph tags.")
out.append("")

out += ["## Pages", "",
        "| URL | Title | T | D | H1 | Schema |",
        "|---|---|---|---|---|---|"]
for p in sorted(pages, key=lambda x: x['url']):
    if p['noindex']:
        out.append(f"| `{p['url']}` | _noindex_ | | | | |"); continue
    schema = ', '.join(t for t in p['schema']
                       if t not in ('ImageObject', 'PostalAddress', 'ContactPoint', 'Country',
                                    'State', 'City', 'AdministrativeArea', 'PropertyValue',
                                    'Place', 'Language', 'ListItem', 'Offer', 'QuantitativeValue',
                                    'UnitPriceSpecification', 'BusinessAudience', 'ServiceChannel',
                                    'Question', 'Answer', 'HowToStep', 'HowToSupply', 'HowToTool',
                                    'MonetaryAmount', 'OfferCatalog', 'Organization', 'WebSite',
                                    'BreadcrumbList', 'Thing'))
    out.append(f"| `{p['url']}` | {(p['title'] or '')[:44]} | {len(p['title'] or '')} | "
               f"{len(p['desc'] or '')} | {'y' if p['h1'] else 'NO'} | {schema} |")

dest = os.path.join(ROOT, '_seo', 'content-inventory.md')
open(dest, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f"Wrote {dest}")
print(f"{len(live)} indexable pages, {len(issues)} issues")
for u, why in sorted(issues)[:20]: print(f"  {u}: {why}")
